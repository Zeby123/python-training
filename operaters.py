#1 Arithmetic operators;
    #used to perform calculations eg; modulus(%), addition(+), floor division(/), subtractions(-), exponentiation(**) etc
    
#2 Comparison operators;
   #used to compare values or variables eg; greater than(>), less than(<), equals to(==) etc
   #return boolean (true or false)
   # create conditions
print(10==10)

#3 Logical Operators 
   #Used to combine conditions
   #and ->returns True if all conditions are true

print(20<10 and 40<50)

   #or ->Returns True if atleast one condition is true
print(20 < 10 or 40 <50)

   #Not ->Inverts the result of a condition

print(not 10>20)

